"""Generate vectors.json: the cross-language test vectors (Python `cryptography` is the reference).

Run from the repo root:
  uv run --no-project --with pydantic --with cryptography python app/fixtures/sinsenal/gen_vectors.py
Keys are TEST-ONLY synthetic keys derived from fixed scalars. ECDSA signatures are randomized, so the
committed vectors.json is the source of truth for the TypeScript tests: regenerate only on a contract change.
Synthetic personas only (Lupita, Mario, Doña Carmen, Luis): no real phones or CLABEs.
"""
import base64
import hashlib
import json
import sys
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric import ec

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from app.schemas import protocol as p  # noqa: E402

_ORDER = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551  # P-256 group order
OUT = Path(__file__).with_name("vectors.json")
WEB_COPY = ROOT / "web" / "src" / "lib" / "contract" / "vectors.json"


def key(label: str) -> dict:
    """Deterministic P-256 private JWK from a label (test-only)."""
    d = int.from_bytes(hashlib.sha256(b"sinsenal-test-key/" + label.encode()).digest(), "big")
    d = d % (_ORDER - 1) + 1
    return p.jwk_from_private(ec.derive_private_key(d, ec.SECP256R1()))


def pub(jwk: dict) -> dict:
    return {k: jwk[k] for k in ("kty", "crv", "x", "y")}


def uid(label: str) -> str:
    return p.bytes_to_ulid(hashlib.sha256(b"sinsenal-id/" + label.encode()).digest()[:16])


def canonical(obj: dict) -> bytes:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()


def b64(b: bytes) -> str:
    return base64.b64encode(b).decode()


def main() -> None:
    server, lupita, mario, carmen = key("server"), key("payer-lupita"), key("payer-mario"), key("merchant-carmen")
    eph = key("ephemeral-envelope")
    payer_id, merchant_id = uid("payer-lupita"), uid("merchant-carmen")
    valid_until = 1794240000  # 2026-11-09, synthetic

    def credential(subject_id, subject_type, jwk, cap) -> dict:
        body = {"subject_id": subject_id, "subject_type": subject_type, "pubkey_jwk": pub(jwk),
                "daily_cap_cents": cap, "valid_until": valid_until, "rep_version": 1}
        return {**body, "server_sig": b64(p.sign(server, canonical(body)))}

    # Challenge (merchant -> payer)
    ch = p.ChallengeFields(1, merchant_id, bytes.fromhex("a1b2c3d4e5f60718"), 1794122700,
                           19_321_000, -99_167_000, 4500)
    ch_raw = p.pack_challenge(ch)
    ch_sig = p.sign(carmen, ch_raw)

    # IOU (payer -> merchant)
    iou = p.IouFields(1, payer_id, merchant_id, 4500, 7, 1794122712, ch.nonce, 19_321_010, -99_167_005)
    raw = p.pack_iou(iou)
    sig = p.sign(lupita, raw)
    signed = raw + sig

    # Envelope (merchant -> server), fixed IV so the vector is stable
    iv = bytes.fromhex("000102030405060708090a0b")
    epk, iv_b64, ct = p.encrypt_envelope(pub(server), signed, eph, iv)

    vectors = {
        "_note": "TEST-ONLY synthetic keys and personas. Generated by gen_vectors.py; see docs/protocolo.md.",
        "personas": {"payer": "Lupita", "other_payer": "Mario", "merchant": "Doña Carmen (stand-in)", "relay": "Luis"},
        "server": {"private_jwk": server, "pubkey_jwk": pub(server)},
        "payer": {"id": payer_id, "display_name": "Lupita", "pubkey_jwk": pub(lupita), "private_jwk": lupita,
                  "credential": credential(payer_id, "payer", lupita, 30000)},
        "other_payer": {"id": uid("payer-mario"), "display_name": "Mario", "pubkey_jwk": pub(mario)},
        "merchant": {"id": merchant_id, "name": "Tienda Doña Carmen", "lat": 19.321, "lon": -99.167,
                     "pubkey_jwk": pub(carmen), "private_jwk": carmen,
                     "credential": credential(merchant_id, "merchant", carmen, 0)},
        "challenge": {"raw_hex": ch_raw.hex(), "sig_rs_hex": ch_sig.hex(), "merchant_id": merchant_id,
                      "nonce_hex": ch.nonce.hex(), "ts": ch.ts, "lat_e6": ch.lat_e6, "lon_e6": ch.lon_e6,
                      "amount_cents": ch.amount_cents},
        "iou": {"raw_hex": raw.hex(), "sig_rs_hex": sig.hex(), "payer_id": payer_id, "merchant_id": merchant_id,
                "amount_cents": iou.amount_cents, "counter": iou.counter, "ts": iou.ts,
                "nonce_hex": iou.nonce.hex(), "lat_e6": iou.lat_e6, "lon_e6": iou.lon_e6},
        "iou_model": {"ver": 1, "payer_id": payer_id, "merchant_id": merchant_id, "amount_cents": iou.amount_cents,
                      "counter": iou.counter, "ts": iou.ts, "nonce": iou.nonce.hex(), "lat": iou.lat_e6 / 1e6,
                      "lon": iou.lon_e6 / 1e6, "sig": b64(sig), "raw": b64(raw)},
        "envelope": {"envelope_id": hashlib.sha256(signed).hexdigest(), "epk_b64": epk, "iv_b64": iv_b64,
                     "ciphertext_b64": ct, "plaintext_hex": signed.hex(), "ephemeral_private_jwk": eph},
    }
    # self-check: Python verifies its own vectors (r||s -> DER inside verify_signature)
    assert p.verify_signature(pub(lupita), raw, sig)
    assert p.verify_signature(pub(carmen), ch_raw, ch_sig)
    assert p.decrypt_envelope(server, epk, iv_b64, ct) == signed
    text = json.dumps(vectors, indent=2, ensure_ascii=False) + "\n"
    OUT.write_text(text)
    WEB_COPY.parent.mkdir(parents=True, exist_ok=True)
    WEB_COPY.write_text(text)
    print(f"wrote {OUT} and {WEB_COPY} ({len(raw)}-byte IOU, {len(signed)}-byte signed)")


if __name__ == "__main__":
    main()
